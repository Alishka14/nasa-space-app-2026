"""Final narration scripts for a voice-over in English, Russian and Kazakh.

    python scripts/build_voiceover.py      # writes docs/video/VOICEOVER_FINAL.md

The narration is the `vo` text of every scene in intro-scripts.json — the same text the films show as
subtitles — with numbers filled from facts.json. This script adds what a speaker needs: how to read each
number and term, and whether the spoken line fits its scene at a calm pace.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from intro_content import LANGS, ROOT, fill, load_facts, load_scripts  # noqa: E402

OUT = ROOT / "docs" / "video" / "VOICEOVER_FINAL.md"

# Calm documentary pace, words per second (rough planning values, not measurements).
RATE = {"en": 2.5, "ru": 2.2, "kk": 2.0}
LANG_NAME = {"en": "English", "ru": "Русский", "kk": "Қазақша"}

# How every number that occurs in the narration is spoken. Keys are the strings as they appear on screen.
READ = {
    "en": {"r =": "r equals", "−0.285": "minus zero point two eight five", "+0.593": "plus zero point five nine three",
           "−0.945": "minus zero point nine four five", "−0.316": "minus zero point three one six",
           "−0.775": "minus zero point seven seven five", "288": "two hundred and eighty-eight"},
    "ru": {"r =": "эр равно", "−0,285": "минус ноль целых двести восемьдесят пять тысячных",
           "+0,593": "плюс ноль целых пятьсот девяносто три тысячных",
           "−0,945": "минус ноль целых девятьсот сорок пять тысячных",
           "−0,316": "минус ноль целых триста шестнадцать тысячных",
           "−0,775": "минус ноль целых семьсот семьдесят пять тысячных", "288": "двести восемьдесят восемь"},
    "kk": {"r =": "эр тең", "−0,285": "минус нөл бүтін мыңнан екі жүз сексен бес",
           "+0,593": "плюс нөл бүтін мыңнан бес жүз тоқсан үш",
           "−0,945": "минус нөл бүтін мыңнан тоғыз жүз қырық бес",
           "−0,316": "минус нөл бүтін мыңнан үш жүз он алты",
           "−0,775": "минус нөл бүтін мыңнан жеті жүз жетпіс бес", "288": "екі жүз сексен сегіз"},
}

GLOSSARY = [
    ("EARTH SENSES", "ERTH SEN-siz — /ɜːθ ˈsɛnsɪz/", "по-английски: «ёрс сéнсиз»", "ағылшынша: «ёрс сенсиз»"),
    ("NASA", "NA-suh — /ˈnæsə/", "«нáса»", "«наса»"),
    ("NASA POWER", "“NASA Power”, as a word", "«нáса пáуэр»", "«наса пауэр»"),
    ("MERRA-2", "“MERRA two” — /ˈmɛrə tuː/", "«мéрра-два»", "«мерра-екі»"),
    ("Pavlodar / Павлодар", "pav-lo-DAR — /ˌpævləˈdɑːr/", "Павлодáр", "Павлодар (екпін соңғы буында)"),
    ("Kazakhstan / Казахстан / Қазақстан", "KAZ-akh-stan — /ˌkæzəkˈstæn/", "Казахстáн", "Қазақстан"),
    ("r (correlation)", "the letter “r”", "«эр»", "«эр»"),
    ("−0.285 → +0.593", "read every digit; never round in speech", "все три знака, без округления", "үш таңбаны толық, дөңгелектемей"),
]


def spoken(text: str, lang: str) -> tuple[str, list[str]]:
    """The line as it is said, and the readings used; numbers without a reading are reported."""
    out, used = text, []
    for key in sorted(READ[lang], key=len, reverse=True):
        if key in out:
            out = out.replace(key, READ[lang][key])
            used.append(key)
    missing = re.findall(r"[−+]?\d+(?:[.,]\d+)?", out)
    if missing:
        raise SystemExit(f"{lang}: no reading for {missing} in: {text}")
    return out, used


def words(text: str) -> int:
    """Spoken words: a hyphenated compound ("wetter-than-usual") is said as several words."""
    return len(re.findall(r"[\w’']+", text))


def build() -> str:
    facts, scripts = load_facts(), load_scripts()
    L = ["# Final voice-over scripts — English, Русский, Қазақша", "",
         "Generated by `scripts/build_voiceover.py` from `frontend/src/onboarding/content/intro-scripts.json` "
         "and `facts.json`; edit the scripts there, not here. The narration is word for word the subtitle text "
         "of the films, so sound and picture never disagree.", "",
         "**Status.** No voice has been recorded. A synthetic voice would need a text-to-speech service; the "
         "ones connected to this workspace use paid credits, which were not spent without the team's approval. "
         "If a synthetic voice is used later, it must be a neutral stock or designed voice — never an imitation "
         "of a real narrator or actor — and the film description must say the voice is synthetic.", "",
         "**How to record.** One take per scene, starting at the scene's start time; leave the scene's last "
         "0.3 s silent. Read numbers in full exactly as below — they must match the screen. "
         f"Planning pace: English {RATE['en']}, Russian {RATE['ru']}, Kazakh {RATE['kk']} words per second; "
         "*fit* compares the spoken length at that pace with the scene.", "",
         "## Pronunciation", "",
         "| Term | English | Русский | Қазақша |", "|---|---|---|---|"]
    L += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in GLOSSARY]
    L += ["", "### Numbers", "", "| On screen | English | Русский | Қазақша |", "|---|---|---|---|"]
    for k_en in READ["en"]:
        k_ru = k_en.replace(".", ",")
        L.append(f"| `{k_en}` | {READ['en'][k_en]} | {READ['ru'].get(k_ru, '')} | {READ['kk'].get(k_ru, '')} |")
    tight = []
    for v in scripts["variants"]:
        total = sum(s["dur"] for s in v["scenes"])
        L += ["", f"## {v['id'].capitalize()} — {total:g} s", ""]
        for lang in LANGS:
            L += [f"### {LANG_NAME[lang]}", "", "| Scene | Time | Narration (as spoken) | Words | Fit |", "|---|---|---|---|---|"]
            t = 0.0
            for s in v["scenes"]:
                line, _ = spoken(fill(s["vo"][lang], facts, lang), lang)
                n = words(line)
                need = n / RATE[lang]
                room = s["dur"] - 0.3
                fit = "ok" if need <= room else f"tight ({need:.1f} s for {room:.1f} s)"
                if need > room:
                    tight.append((v["id"], lang, s["id"], need, room))
                L.append(f"| {s['id']} | {t:.1f}–{t + s['dur']:.1f} s | {line} | {n} | {fit} |")
                t += s["dur"]
            L.append("")
    L += ["## Lines that do not fit their scene when spoken in full", "",
          "The scene lengths were set for reading subtitles (at most 16.5 characters per second), not for speaking "
          "every number in full. A voiced version therefore needs one of two things before recording: longer "
          "scenes for the lines below (change `dur` in intro-scripts.json and re-render), or a narrator who does "
          "not repeat a number that the title already shows. Do not speed the voice up to make it fit.", ""]
    if tight:
        L += ["| Film | Language | Scene | Needs | Room |", "|---|---|---|---|---|"]
        L += [f"| {a} | {b} | {c} | {d:.1f} s | {e:.1f} s |" for a, b, c, d, e in tight]
    else:
        L.append("None.")
    return "\n".join(L) + "\n"


def main() -> int:
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
