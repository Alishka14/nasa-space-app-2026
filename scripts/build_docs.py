"""Regenerate the documents that are pure renderings of engine output:
docs/EVIDENCE_LEDGER.md and docs/reports/*.md.

Run from the repository root:  python scripts/build_docs.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from earth_senses.evidence import ledger_markdown, load_independent_reports  # noqa: E402
from earth_senses.investigate import compare_regions, investigate  # noqa: E402
from earth_senses.power_client import PowerStore  # noqa: E402
from earth_senses.report import render_report  # noqa: E402

VARS = ["T2M", "RH2M", "PRECTOTCORR"]
PAV = {"name": "Pavlodar, Kazakhstan", "latitude": 52.29, "longitude": 76.97}
ALM = {"name": "Almaty, Kazakhstan", "latitude": 43.24, "longitude": 76.95}


def main() -> int:
    store = PowerStore(ROOT / "data", allow_network=False)
    reports = load_independent_reports(ROOT / "data" / "independent_reports")
    cases = [
        ("pavlodar_2001-2024", PAV, 2001, 2024, "Pavlodar 2001–2024 (the case Gemini analysed)"),
        ("pavlodar_1981-2024", PAV, 1981, 2024, "Pavlodar 1981–2024 (longer record: period-sensitivity check)"),
        ("almaty_2001-2024", ALM, 2001, 2024, "Almaty grid cell 2001–2024 (second region)"),
    ]
    (ROOT / "docs" / "reports").mkdir(parents=True, exist_ok=True)
    parts = ["# Evidence Ledger", "",
             "> Generated by `scripts/build_docs.py`. Do not edit by hand.", "",
             "Every record below was computed by the EARTH SENSES engines from the raw NASA files in `data/raw` "
             "(SHA-256 in `data/provenance`). Record ids are derived from the claim type, region, period, variables, "
             "method, parameters and data hash: the same inputs always give the same id.", "",
             "Status ladder (MIZAN): `HYPOTHESIS` → `OBSERVED` → `REPLICATED` → `PRACTICALLY_VALIDATED` → "
             "`TRANSFER_VALIDATED`. The engine assigns only `OBSERVED` and `HYPOTHESIS`. `REPLICATED` appears only where "
             "a value reported independently (here: by Gemini, for Pavlodar 2001–2024) agrees with ours; it covers the "
             "number, not any interpretation. Nothing in this ledger is above `REPLICATED`.", ""]
    for slug, reg, start, end, title in cases:
        inv = investigate(store, lat=reg["latitude"], lon=reg["longitude"], start=start, end=end, variables=VARS,
                          region_name=reg["name"], independent_reports=reports)
        (ROOT / "docs" / "reports" / f"{slug}.md").write_text(render_report(inv), encoding="utf-8")
        counts: dict[str, int] = {}
        for e in inv["evidence"]:
            counts[e["status"]] = counts.get(e["status"], 0) + 1
        body = ledger_markdown(inv["evidence"], title=title).replace("# ", "## ", 1).replace("\n## EV-", "\n### EV-")
        parts += [body, f"Records: {len(inv['evidence'])} ({', '.join(f'{k} {v}' for k, v in sorted(counts.items()))}). "
                        f"Data hash `{inv['data_hash']}`.", ""]
        print(f"{slug}: {len(inv['evidence'])} records {counts}")

    cmp_ = compare_regions(store, PAV, ALM, start=2001, end=2024, variables=VARS)
    parts += ["## Region comparison: Pavlodar vs Almaty grid cell, 2001–2024", "",
              "| Variable | Verdict | Statement |", "|---|---|---|"]
    for v in cmp_["variables"]:
        parts.append(f"| {v['variable']} | {v['verdict']} | {v['statement']} |")
    parts += ["", f"Grid-cell mean elevations: {cmp_['region_a']['grid_cell_elevation_m']} m and "
                  f"{cmp_['region_b']['grid_cell_elevation_m']} m. The Almaty cell averages mountains and plain and does "
                  "not represent the city.", ""]
    (ROOT / "docs" / "EVIDENCE_LEDGER.md").write_text("\n".join(parts), encoding="utf-8")
    print("wrote docs/EVIDENCE_LEDGER.md and docs/reports/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
